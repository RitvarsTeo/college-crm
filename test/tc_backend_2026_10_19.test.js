test('CSV: quotes, doubled quotes, commas and line breaks inside a field, a BOM, CRLF', () => {
  const rows = tcimport.parseCsv('\uFEFFa,b,c\r\n1,"x, ""y""\nz",3\r\n\r\n4,,6\r\n');
  assert.deepEqual([...rows], [{ a: '1', b: 'x, "y"\nz', c: '3' }, { a: '4', b: '', c: '6' }]);
  assert.deepEqual(rows.columns, ['a', 'b', 'c']);
  assert.deepEqual(tcimport.parseCsv('a,b\r\n').columns, ['a', 'b'], 'the header of a file with no rows');
  assert.throws(() => tcimport.parseCsv('a\n"open'), /never closed/);
});

test('PREVIEW: counts only, writes nothing, and the rules are the written ones', async () => {
  const db = await openDb();
  const { files, facts } = synthFiles({ today: TODAY });
  const { counts } = await tcimport.preview(db, files, { today: TODAY });
  assert.equal(await count(db, 'tc_companies'), 0, 'nothing written');
  assert.equal(counts.companies.inFile, 40);
  assert.equal(counts.companies.new, 40);
  assert.equal(counts.companies.rejected, 0);
  const json = JSON.stringify(counts);
  for (const k of facts.contacts.filter((x) => x.name || x.email)) {
    assert.ok(!json.includes(k.name || '\u0000') && !json.includes(k.email || '\u0000'), 'no contact name or email in the preview');
  }
  // no status in the Excel starts as not_contacted, shown "No status yet" (the owner, 26.10.2026; config/tc.json)
  const notSet = facts.companies.filter((c) => c.status === 'not_set').length;
  assert.ok(notSet > 0);
  assert.equal(counts.statuses.not_contacted, facts.companies.filter((c) => ['not_set', 'not_contacted'].includes(c.status)).length);
  // a filler date before 2000 is not known: never imported as a date
  assert.equal(counts.lastCommunication, facts.companies.filter((c) => c.last_communication && c.last_communication >= '2000').length);
  assert.equal(counts.next.inFile, facts.companies.filter((c) => c.next_communication && c.next_communication >= '2000').length);
  assert.equal(counts.next.overdueOnDayOne, facts.companies.filter((c) => c.next_communication >= '2000' && c.next_communication < TODAY).length);
  // courses: the main tab only, the highest count per year; the side tab is counted, not imported
  assert.equal(counts.courses.sideTabLinesNotImported, facts.courses.filter((k) => k.is_primary === '0').length);
  assert.equal(counts.courses.delegates, facts.courses.filter((k) => k.is_primary === '1').reduce((n, k) => n + Number(k.count), 0));
  const active = new Set(facts.courses.filter((k) => k.is_primary === '1' && Number(k.count) > 0).map((k) => k.company_id));
  assert.equal(counts.courses.activeClients, active.size, 'active client = any company with a delegate in any year');
  assert.match(counts.hash, /^[0-9a-f]{64}$/);
});

test('APPLY: only with the preview\'s hash, one transaction, every row traced, and a second apply finds nothing', async () => {
  const db = await openDb();
  const { files } = synthFiles({ today: TODAY });
  await assert.rejects(tcimport.apply(db, files, { today: TODAY }), /preview first/);
  await assert.rejects(tcimport.apply(db, files, { hash: 'f'.repeat(64), today: TODAY }), /not the ones previewed/);
  assert.equal(await count(db, 'tc_companies'), 0, 'a refused apply wrote nothing');
  const { counts } = await tcimport.preview(db, files, { today: TODAY });
  // a different option is a different preview
  await assert.rejects(tcimport.apply(db, files, { hash: counts.hash, pastNext: 'skip', today: TODAY }), /not the ones previewed/);
  const r = await tcimport.apply(db, files, { hash: counts.hash, today: TODAY }, 'tester');
  assert.equal(r.applied, true);
  assert.equal(await count(db, 'tc_companies'), 40);
  assert.equal(await count(db, 'tc_import_rows'), 40);
  assert.equal(await count(db, 'tc_company_contacts'), counts.contacts.toImport);
  assert.equal(await count(db, 'tc_company_courses'), counts.courses.companyYears);
  assert.equal(await count(db, 'tc_tasks'), counts.next.toImport);
  const importLines = await db.prepare(`SELECT body FROM tc_activities WHERE kind = 'import'`).all();
  assert.equal(importLines.length, 40, 'each company says where it came from');
  assert.match(importLines[0].body, /^Imported from Planning of customers\.xlsx, row \d+$/);
  const again = await tcimport.preview(db, files, { today: TODAY });
  assert.equal(again.counts.companies.new, 0);
  assert.equal(again.counts.companies.alreadyImported, 40);
  await tcimport.apply(db, files, { hash: again.counts.hash, today: TODAY }, 'tester');
  assert.equal(await count(db, 'tc_companies'), 40, 'idempotent');
  assert.equal(await count(db, 'tc_company_contacts'), counts.contacts.toImport);
});

