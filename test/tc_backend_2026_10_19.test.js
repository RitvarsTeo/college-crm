  const { files } = synthFiles({ today: new Date().toISOString().slice(0, 10) });
  const [st0, refused] = await post('/api/admin/tc/import', { files }, { 'x-acting-as': 'Ieva', 'content-type': 'application/json' });
  assert.equal(st0, 403, 'not an admin: ' + refused.error);
  const [st1, pv] = await post('/api/admin/tc/import', { files });
  assert.equal(st1, 200);
  assert.equal(pv.preview, true);
  assert.equal(pv.companies.new, 40);
  const [st2, noHash] = await post('/api/admin/tc/import', { files, apply: true });
  assert.equal(st2, 400);
  assert.match(noHash.error, /preview first/);
  const [st3, done] = await post('/api/admin/tc/import', { files, apply: true, hash: pv.hash });
  assert.equal(st3, 200);
  assert.equal(done.applied, true);
  const [, status] = await get('/api/admin/tc/import');
  assert.deepEqual(status.done, { created: 40 });
  const [, home] = await get('/api/tc/home');
