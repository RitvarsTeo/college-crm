test('an exhibition\'s columns: a move and a removal are lines in the company\'s log; nothing is deleted', async () => {
  const { db, ids } = await seasonWorld();
  await ss.seedApply(db, { hash: (await ss.seedPreview(db)).hash }, 'admin');
  const ham = (await db.prepare(`SELECT id FROM tc_events WHERE source_key = 'windenergy_hamburg_2026'`).get()).id;
  const link = (await db.prepare('SELECT id FROM tc_event_companies WHERE event_id = ? AND company_id = ?').get(ham, ids.h)).id;
  await assert.rejects(ss.setStage(db, link, 'sent', 'Aleksandrs'), /Pick one of/);
  await ss.setStage(db, link, 'met', 'Aleksandrs');
  await ss.setStage(db, link, 'booked', 'Aleksandrs');
  const page = await ss.eventPage(db, ham);
  assert.deepEqual(page.columns.map((c) => c.cards.length), [2, 0, 0, 1]);
  const log = await db.prepare(`SELECT old_value, new_value, actor FROM tc_activities WHERE company_id = ? AND field = 'event' ORDER BY id`).all(ids.h);
  assert.deepEqual(log.map((l) => [l.old_value, l.new_value]), [
    ['WindEnergy Hamburg: On the list', 'WindEnergy Hamburg: Met at the stand'],
    ['WindEnergy Hamburg: Met at the stand', 'WindEnergy Hamburg: Booked a course']]);
  await assert.rejects(ss.addToEvent(db, ham, { companyId: ids.h }, 'Aleksandrs'), /already on the list/);
  await ss.removeFromEvent(db, link, 'Aleksandrs');
  assert.equal(await count(db, 'tc_event_companies', `id = ${link} AND removed_at IS NOT NULL`), 1, 'stamped, not deleted');
  await ss.addToEvent(db, ham, { companyId: ids.h }, 'Aleksandrs');
  assert.equal((await ss.eventPage(db, ham)).columns[0].cards.length, 3, 'back on the list, in the first column');
  await ss.editEvent(db, ham, { startsOn: '2026-09-23', endsOn: '2026-09-26', dateConfirmed: true }, 'admin');
  await assert.rejects(ss.editEvent(db, ham, { startsOn: '2026-09-23', endsOn: '2026-09-01' }, 'admin'), /before the first/);
  assert.equal((await ss.eventPage(db, ham)).startsOn, '2026-09-23');
});

