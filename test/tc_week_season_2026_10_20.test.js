test('the week: Mon-Fri, a contact not done on Monday is in today\'s column "from Mon", no late figure anywhere', async () => {
  const { db, a } = await world();
  const w = await wk.week(db, { me: ME, now: TUE });
  assert.equal(w.monday, '2026-10-19');
  assert.equal(w.friday, '2026-10-23');
  assert.deepEqual(w.days.map((d) => `${d.dow} ${d.n}`), ['Mon 19', 'Tue 20', 'Wed 21', 'Thu 22', 'Fri 23']);
  assert.equal(w.days[1].today, true);
  const tue = w.days[1].cards;
  assert.deepEqual(tue.map((c) => [c.name, c.from]), [['Baltic Shipping Services', 'Mon'], ['Essberger', null]], 'the carried one first, marked from Mon');
  assert.equal(tue[0].companyId, a);
  assert.equal(tue[0].topic, '2027 training plan');
  assert.deepEqual(w.days[0].cards.map((c) => [c.name, c.done, c.result]), [['Columbia CSM', true, 'Reached']], 'done on Monday: a grey Logged card');
  assert.deepEqual(w.days[3].cards.map((c) => c.kindLabel), ['Meeting']);
  assert.ok(!JSON.stringify(w).match(/overdue|late/i), 'no late or overdue anything in the answer');
  assert.ok(!w.days.some((d) => d.cards.some((c) => c.name === 'Someone Else Ltd')), 'Mine: not somebody else\'s');
  const team = await wk.week(db, { me: ME, scope: 'team', now: TUE });
  assert.deepEqual(team.days[2].cards.map((c) => [c.name, c.ownerInitials]), [['Someone Else Ltd', 'LM']]);
  // the week before: the carried contact lives in today, not in the past; next week: nothing carried
  const before = await wk.week(db, { me: ME, from: '2026-10-12', now: TUE });
  assert.equal(before.days.flatMap((d) => d.cards).length, 0);
  const after = await wk.week(db, { me: ME, from: '2026-10-26', now: TUE });
  assert.equal(after.days.flatMap((d) => d.cards).length, 0);
  assert.equal(after.thisWeek, false);
});

