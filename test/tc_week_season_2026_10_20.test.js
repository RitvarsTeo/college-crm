  const db = await openDb();
  const ids = {};
  ids.h = await company(db, 'Global Wind Service', { country: 'Denmark', extra: EX.hamburg, courses: { 2025: 487 } });
  ids.b = await company(db, 'Boskalis', { country: 'Netherlands', extra: EX.both, courses: { 2024: 100 } });
  ids.d = await company(db, 'Donsö Shipping', { country: 'Sweden', extra: EX.donso });
