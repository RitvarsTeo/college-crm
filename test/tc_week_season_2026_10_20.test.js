test('the seed: the preview counts per event and writes nothing; the apply needs the hash and runs once', async () => {
  const { db, ids } = await seasonWorld();
  const pv = await ss.seedPreview(db);
  const by = Object.fromEntries(pv.events.map((e) => [e.key, [e.companies, e.counted]]));
  assert.deepEqual(by, { windenergy_hamburg_2026: [3, 2], oeec_amsterdam_2026: [1, 1], wind_europe_2027: [1, 1], donso_2027: [1, 1], calendars_2026: [2, 2] },
    'Hamburg 3 on the list, 2 counted (the TOTAL row is not); Donsö matched through the broken letter');
  assert.deepEqual(pv.unmatched, [{ text: 'Posidonia Athens', n: 1 }]);
  assert.equal(await count(db, 'tc_events'), 0, 'the preview writes nothing');
  await assert.rejects(ss.seedApply(db, {}, 'admin'), /preview first/);
  await assert.rejects(ss.seedApply(db, { hash: 'x' + pv.hash.slice(1) }, 'admin'), /not the ones previewed/);
  const r = await ss.seedApply(db, { hash: pv.hash }, 'admin');
  assert.deepEqual([r.events, r.companies], [5, 8]);
  await assert.rejects(ss.seedApply(db, { hash: pv.hash }, 'admin'), /already run/);
  assert.equal(await count(db, 'tc_event_companies'), 8);
  assert.ok((await ss.seedPreview(db)).applied, 'the preview says it has run');
  const ham = await db.prepare(`SELECT id FROM tc_events WHERE source_key = 'windenergy_hamburg_2026'`).get();
  const page = await ss.eventPage(db, ham.id);
  assert.deepEqual(page.columns.map((c) => c.label), ['On the list', 'Met at the stand', 'Follow-up sent', 'Booked a course']);
  assert.deepEqual(page.columns[0].cards.map((c) => [c.name, c.client, c.delegates]),
    [['Global Wind Service', true, 487], ['Boskalis group', true, 300], ['Boskalis', true, 100]]);
  assert.deepEqual([page.companies, page.clients], [2, 2], 'the TOTAL row is on the list but not counted');
  assert.equal(page.columns[0].cards.find((c) => c.companyId === ids.t).counted, false);
});

