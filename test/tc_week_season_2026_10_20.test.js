async function company(db, name, { country = 'Latvia', pic = null, picEmail = null, extra = null, courses = {} } = {}) {
  const { id } = await tc.addCompany(db, { name, country }, 'tester');
  await db.prepare('UPDATE tc_companies SET pic_name = ?, pic_email = ?, extra = ? WHERE id = ?').run(pic, picEmail, extra ? JSON.stringify(extra) : null, id);
  for (const [y, n] of Object.entries(courses)) {
    await db.prepare(`INSERT INTO tc_company_courses (company_id, year, attendees, recorded_at) VALUES (?,?,?,?)`).run(id, Number(y), n, '2025-09-24');
  }
  return id;
}
const task = (db, companyId, due, extra = {}) => db.prepare(`INSERT INTO tc_tasks (company_id, label, due_at, owner, created_at, created_by, kind, done_at, outcome, result)
  VALUES (?,?,?,?,?,?,?,?,?,?)`).run(companyId, extra.label || 'Next communication', due, extra.owner || null, '2026-10-01T00:00:00Z', 'tester',
  extra.kind || null, extra.done || null, extra.outcome || null, extra.result || null);

